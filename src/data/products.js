export const getFeaturedProducts = () => products.filter((p) => p.featured);
export const getProductsByCategory = (cat) => products.filter((p) => p.category === cat);
export const getProductById = (id) => products.find((p) => p.id === id);
export const getAllCategories = () => [...new Set(products.map((p) => p.category))];
export const getAllSubCategories = (cat) => [...new Set(products.filter((p) => !cat || p.category === cat).map((p) => p.subCategory))];
